def fr(texto: str | None) -> str | None:
    if not texto:
        return texto
    return _RX.sub(lambda m: FR[m.group(0)], texto)


def traduzir(resultado: dict, lang: str) -> dict:
    """Traduz o resultado de mapa_materiais.mapa() para a língua do documento (pt = sem alteração)."""
    if lang != "fr":
        return resultado
    out = {**resultado, "aviso": fr(resultado.get("aviso"))}
    out["artigos"] = [{**a, "motivo": fr(a.get("motivo")), "perfil_tipo": fr(a.get("perfil_tipo")),
                       "materiais": [{**m, **{k: fr(m.get(k)) for k in ("material", "fonte", "em_falta", "embalagens")}} for m in a["materiais"]]}
                      for a in resultado["artigos"]]
    out["totais"] = sorted(({**t, "material": fr(t["material"])} for t in resultado["totais"]), key=lambda t: t["material"].lower())
    return out
