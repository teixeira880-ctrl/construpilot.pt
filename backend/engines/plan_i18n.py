def localize_plan(plan: dict, lang: str) -> dict:
    """Retourne le plan avec name/tagline/description/badge/features traduits si dispo."""
    if not lang or lang == "fr":
        return plan
    tr = PLAN_I18N.get(lang, {}).get(plan.get("plan_id"))
    if not tr:
        return plan
    out = dict(plan)
    for key in ("name", "tagline", "description", "badge", "features"):
        if key in tr:
            out[key] = tr[key]
    return out
