TASKS_BY_KEY = {t["key"]: t for t in TASKS}


def build_guide(task_key: str, params: dict | None = None) -> dict:
    task = TASKS_BY_KEY.get(task_key)
    if not task:
        raise KeyError(task_key)
    materials, calc = [], None
    if task["calculator"]:
        cfg = calculators.CALCULATORS[task["calculator"]]
        args = {f["name"]: f.get("default") for f in cfg["fields"]}
        args.update(task["calc_defaults"])
        args.update({k: v for k, v in (params or {}).items() if k in args})
        args = {k: v for k, v in args.items() if v is not None}
        calc = cfg["fn"](**args)
        materials = calc["materials"]
    return {
        "key": task["key"], "name": task["name"], "difficulty": task["difficulty"],
        "difficulty_label": DIFFICULTY[task["difficulty"]]["label"],
        "difficulty_color": DIFFICULTY[task["difficulty"]]["color"],
        "duration": task["duration"], "lot": task["lot"], "safety": task["safety"],
        "steps": task["steps"], "materials": materials, "calculation": calc,
        "pro_recommended": task["difficulty"] == "pro",
    }
