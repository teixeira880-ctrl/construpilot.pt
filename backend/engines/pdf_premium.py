def lang_of(lang: str | None, country: str | None = None) -> str:
    """Língua do acabamento. No .pt, "fr" sozinho = português (código histórico); francês verdadeiro = "fr-FR"."""
    raw = (lang or "").lower().replace("_", "-")
    if raw.startswith("fr-"):
        return "fr"
    if raw[:2] in ("en", "uk"):
        return raw[:2]
    if not raw and str(country or "").upper() == "FR":
        return "fr"
    return "pt"


def _hex(c: str) -> tuple:
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) / 255 for i in (0, 2, 4))


def empresa(branding: dict | None) -> dict:
    b = branding or {}
    raw = str(b.get("accent_color") or "").strip()
    try:
        cor = _hex(raw) if len(raw) == 7 and raw.startswith("#") else _hex(COR_PADRAO)
    except ValueError:
        cor = _hex(COR_PADRAO)
    logo = None
    lb = b.get("logo_b64")
    if lb:
        try:
            logo = base64.b64decode(str(lb).split(",", 1)[-1])
            import pymupdf
            pymupdf.Pixmap(logo)                                  # imagem válida?
        except Exception:  # noqa: BLE001
            logo = None
    site = b.get("website") or b.get("public_website") or ""
    if not site:
        m = re.search(r"\b([\w-]+\.[a-z]{2,}(?:\.[a-z]{2})?)\b", str(b.get("contact_line") or ""))
        site = m.group(1) if m and "@" not in m.group(0) else ""
    return {"nome": str(b.get("company_name") or "").strip(), "cor": cor, "logo_bytes": logo,
            "site": re.sub(r"^https?://", "", str(site)).rstrip("/")}


def ativo(branding: dict | None) -> bool:
    return (branding or {}).get("premium_pdf", True) is not False


def _fontes():
    from engines.calc_lots.gros_oeuvre import _fontes as f
    return f()


def _quebra(s, n, max_linhas=4):
    out, linha = [], ""
    for w in str(s or "").split():
        if len(linha) + len(w) + 1 > n and linha:
            out.append(linha)
            linha = w
        else:
            linha = (linha + " " + w).strip()
    if linha:
        out.append(linha)
    return out[:max_linhas]


def _logo_rect(pw, ph, x, y, wmax, hmax, alinhar="esq"):
    k = min(wmax / pw, hmax / ph)
    w, h = pw * k, ph * k
    if alinhar == "dir":
        x -= w
    return (x, y, x + w, y + h)


def _opaco(png: bytes, alpha: float) -> bytes:
    import pymupdf
    pix = pymupdf.Pixmap(png)
    if pix.colorspace and pix.colorspace.n != 3:
        pix = pymupdf.Pixmap(pymupdf.csRGB, pix)
    if not pix.alpha:
        pix = pymupdf.Pixmap(pix, 1)
    s = bytearray(pix.samples)
    for i in range(pix.n - 1, len(s), pix.n):
        s[i] = int(s[i] * alpha)
    return pymupdf.Pixmap(pix.colorspace, pix.width, pix.height, bytes(s), True).tobytes("png")


def _paginas_de(src, titulos: list[str]) -> list[tuple[str, int | str]]:
    """Página (na versão final, capa = 1) onde cada título aparece pela primeira vez."""
    out = []
    textos = [p.get_text().lower() for p in src]
    for t in titulos:
        k = str(t).strip()
        if not k:
            continue
        pg = next((i for i, tx in enumerate(textos) if k.lower()[:40] in tx), None)
        if pg is not None:
            out.append((k, pg + 2))
    return out


def acabar(pdf: bytes, capa: dict, branding: dict | None, lang: str = "pt", paginas: str = "completo") -> bytes:
    """capa = {titulo, tipo, subtitulo, local, data, kpis:[(rótulo, valor, unidade)], indice:[títulos], imagem:bytes|None}.
    paginas = "completo" (logótipo no rodapé + marca d'água + numeração) ou "leve" (só filete + numeração: o documento já
    tem cabeçalho, rodapé e marca d'água próprios)."""
    if not ativo(branding):
        return pdf
    try:
        return _acabar(pdf, capa, branding, lang, paginas)
    except Exception:  # noqa: BLE001 — o acabamento nunca impede a entrega do documento
        log.warning("pdf premium finishing failed", exc_info=True)
        return pdf


def _acabar(pdf: bytes, capa: dict, branding: dict | None, lang: str, paginas: str) -> bytes:
    import pymupdf
    T = TXT.get(lang, TXT["pt"])
    emp = empresa(branding)
    cor, logo, nome = emp["cor"], emp["logo_bytes"], emp["nome"]
    fr, fb = _fontes()
    src = pymupdf.open(stream=pdf, filetype="pdf")
    if logo:
        lp = pymupdf.Pixmap(logo)
        lw, lh = lp.width, lp.height
    out = pymupdf.open()
    W, H = 595.28, 841.89
    pg = out.new_page(width=W, height=H)
    pg.insert_font(fontname="cr", fontfile=fr)
    pg.insert_font(fontname="cb", fontfile=fb)

    def t(x, y, s, size, c=ESCURO, bold=False, page=pg):
        page.insert_text((x, y), str(s), fontname="cb" if bold else "cr", fontsize=size, color=c)

    # ---------------------------------------------------------------- capa
    pg.draw_rect(pymupdf.Rect(0, 0, W, H), color=None, fill=(0.985, 0.98, 0.972))
    pg.draw_rect(pymupdf.Rect(0, 0, W, 300), color=None, fill=ESCURO)
    pg.draw_rect(pymupdf.Rect(0, 296, W, 304), color=None, fill=cor)
    imagem = capa.get("imagem")
    if imagem:
        pg.insert_image(pymupdf.Rect(0, 0, W, 296), stream=imagem, keep_proportion=False)
        pg.draw_rect(pymupdf.Rect(0, 0, W * 0.62, 296), color=None, fill=ESCURO, fill_opacity=0.72)
    elif len(src):
        sp = src[0]
        mini = sp.get_pixmap(dpi=60)
        r = pymupdf.Rect(W * 0.52, 30, W - 30, 280)
        pg.draw_rect(r, color=None, fill=(1, 1, 1), fill_opacity=0.96)
        pg.insert_image(r + (6, 6, -6, -6), pixmap=mini, keep_proportion=True)
    if logo:
        pg.draw_rect(pymupdf.Rect(30, 34, 210, 100), color=None, fill=(1, 1, 1))
        pg.insert_image(pymupdf.Rect(*_logo_rect(lw, lh, 40, 42, 160, 50)), stream=logo)
    t(30, 140, "ConstruPilot", 11, (0.85, 0.85, 0.85), True)
    if nome:
        t(30, 156, "× " + nome[:40], 11, cor, True)
    t(30, 184, str(capa.get("tipo") or "").upper(), 8.5, (0.75, 0.75, 0.75), True)
    y = 205
    largura = 22 if not imagem else 30
    for linha in _quebra(capa.get("titulo") or capa.get("tipo") or "", largura, 3):
        t(30, y, linha, 17, (1, 1, 1), True)
        y += 21
    for linha in _quebra(capa.get("subtitulo", ""), 48, 3):
        t(30, y + 6, linha, 9, (0.80, 0.80, 0.80))
        y += 12
    for i, linha in enumerate(_quebra(capa.get("local", ""), 90, 2)):
        t(30, 340 + i * 15, linha, 12, ESCURO, True)
    t(30, 372 if len(_quebra(capa.get("local", ""), 90, 2)) > 1 else 358, capa.get("data", ""), 9, CINZA)
    kp = [k for k in (capa.get("kpis") or []) if k and str(k[1]).strip()][:8]
    cw = (W - 60 - 3 * 10) / 4
    y0 = 392
    for i, (rot, val, un) in enumerate(kp):
        cx = 30 + (i % 4) * (cw + 10)
        cy = y0 + (i // 4) * 92
        pg.draw_rect(pymupdf.Rect(cx, cy, cx + cw, cy + 80), color=(0.88, 0.88, 0.88), fill=(1, 1, 1), width=0.6)
        pg.draw_rect(pymupdf.Rect(cx, cy, cx + 4, cy + 80), color=None, fill=cor)
        t(cx + 12, cy + 18, str(rot)[:26], 7, CINZA)
        sv = str(val)[:16]
        t(cx + 12, cy + 48, sv, 17 if len(sv) <= 9 else 12, ESCURO, True)
        t(cx + 12, cy + 66, str(un)[:28], 7, CINZA)
    iy = y0 + 92 * ((len(kp) + 3) // 4) + 18
    ind = _paginas_de(src, capa.get("indice") or [])[:26]
    if ind:
        t(30, iy, T["contents"], 11, ESCURO, True)
        iy += 18
        passo = min(14.0, (H - 70 - iy) / max(1, len(ind)))
        fs = max(6.0, min(8.5, passo - 1.6))
        for tt, pnum in ind:
            t(42, iy, str(tt)[:80], fs, ESCURO)
            if pnum != "":
                t(W - 50, iy, str(pnum), fs, CINZA, True)
            pg.draw_line((42 + min(len(str(tt)[:80]) * fs * 0.52, 380), iy - 2), (W - 58, iy - 2), color=(0.82, 0.82, 0.82),
                         width=0.4, dashes="[1 2] 0")
            iy += passo
    pg.draw_rect(pymupdf.Rect(0, H - 48, W, H), color=None, fill=ESCURO)
    rod = "ConstruPilot · " + T["site"] + (f"   |   {nome}" + (f" · {emp['site']}" if emp["site"] else "") if nome else "")
    t(30, H - 24, rod[:120], 8, (0.9, 0.9, 0.9))
    t(30, H - 12, T["disclaimer"], 5.8, (0.65, 0.65, 0.65))
    # ---------------------------------------------------------------- páginas
    out.insert_pdf(src)
    n = len(out)
    wm = _opaco(logo, 0.06) if (logo and paginas == "completo") else None
    for i in range(1, n):
        p = out[i]
        r = p.rect
        p.insert_font(fontname="cr", fontfile=fr)
        if logo and paginas == "completo":
            p.insert_image(pymupdf.Rect(*_logo_rect(lw, lh, r.width / 2 - 14 * 2.835, r.height - 11.5 * 2.835, 28 * 2.835, 7 * 2.835)),
                           stream=logo)
            wr = pymupdf.Rect(r.width * 0.18, r.height * 0.40, r.width * 0.82, r.height * 0.40 + (r.width * 0.64) * lh / lw)
            p.insert_image(wr, stream=wm, overlay=False)
        if paginas == "completo":                       # "leve": o documento já tem a sua numeração
            p.insert_text((r.width - 80, r.height - 8), f"{T['page']} {i + 1} / {n}", fontname="cr", fontsize=7, color=CINZA)
        p.draw_rect(pymupdf.Rect(0, r.height - 3, r.width, r.height), color=None, fill=cor)
    out.set_metadata({"title": str(capa.get("titulo") or ""), "author": "ConstruPilot" + (f" × {nome}" if nome else ""),
                      "subject": str(capa.get("subtitulo") or capa.get("tipo") or ""), "creator": "ConstruPilot"})
    toc = [[1, T["cover"], 1]] + [[1, str(tt), int(pn)] for tt, pn in ind if isinstance(pn, int)]
    try:
        out.set_toc(toc)
    except Exception:  # noqa: BLE001
        pass
    return out.tobytes(garbage=3, deflate=True)


# ---------------------------------------------------------------- formatação
def _n(x, lang, d=0) -> str:
    try:
        s = f"{float(x):,.{d}f}"
    except (TypeError, ValueError):
        return ""
    if lang == "en":
        return s
    return s.replace(",", " ").replace(".", ",")


def _eur(x, lang) -> tuple[str, str]:
    """Valor compacto para cartão: 12 345 → ('12 345', '€'); 1 234 567 → ('1,23 M', '€')."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "", ""
    if abs(v) >= 1e6:
        return _n(v / 1e6, lang, 2) + " M", "€"
    return _n(v, lang, 0), "€"


# ---------------------------------------------------------------- orçamentos / devis (engines.pdf_docs)
def acabar_orcamento(pdf: bytes, doc: dict, branding: dict | None, lang: str | None) -> bytes:
    lg = lang_of(lang, (branding or {}).get("country"))
    T = TXT[lg]
    tot = doc.get("totals") or {}
    raw_lines = [ln for ln in doc.get("lines") or [] if isinstance(ln, dict)]
    lines = [ln for ln in raw_lines if ln.get("kind") in (None, "line")]
    try:
        from engines.pdf_docs import _lot_breakdown
        from engines.pdf_i18n import pdf_labels
        lots = [n for n, v in _lot_breakdown(raw_lines, pdf_labels(lang)) if abs(v) > 0.005]
    except Exception:  # noqa: BLE001
        lots = []
    ttc, ht = _eur(tot.get("ttc"), lg), _eur(tot.get("ht"), lg)
    kpis = [(T["total_ttc"], ttc[0], ttc[1]), (T["total_ht"], ht[0], ht[1]),
            (T["lines"], str(len(lines)), T["items"])]
    if len(lots) >= 2:
        kpis.append((T["lots"], str(len(lots)), ""))
    vd = doc.get("validity_days")
    if isinstance(vd, (int, float)) and vd > 0:
        kpis.append((T["valid"], str(int(vd)), T["days"]))
    cli = doc.get("client") or {}
    cli_nome = cli.get("name") or cli.get("company") or cli.get("nom") or ""
    site = doc.get("site_address") or doc.get("worksite_address") or cli.get("address") or ""
    imagem = None
    if doc.get("attachment_image_b64"):
        try:
            imagem = base64.b64decode(str(doc["attachment_image_b64"]).split(",", 1)[-1])
        except Exception:  # noqa: BLE001
            imagem = None
    capa = {"tipo": T["quote"] + (f" n.º {doc['number']}" if doc.get("number") and lg == "pt" else
                                  f" {doc['number']}" if doc.get("number") else ""),
            "titulo": doc.get("title") or T["quote"],
            "subtitulo": (f"{T['client']}: {cli_nome}" if cli_nome else ""),
            "local": site, "data": str(doc.get("issue_date") or "")[:10], "kpis": kpis, "indice": lots, "imagem": imagem}
    return acabar(pdf, capa, branding, lg, paginas="leve")


# ---------------------------------------------------------------- medições (engines.pdf_takeoff)
def acabar_medicao(pdf: bytes, plan: dict, takeoff: dict, branding: dict | None, lang: str | None = None) -> bytes:
    lg = lang_of(lang, (branding or {}).get("country"))
    T = TXT[lg]
    tt = takeoff.get("totals") or {}
    kpis = [(T["floor"], _n(tt.get("floor_m2"), lg, 1), "m²"), (T["walls"], _n(tt.get("walls_net_m2"), lg, 1), "m²"),
            (T["rooms"], str(takeoff.get("room_count") or len(takeoff.get("rooms") or [])), T["measured"]),
            (T["perimeter"], _n(tt.get("perimeter_m"), lg, 1), "m")]
    if tt.get("ceiling_m2"):
        kpis.append((T["ceiling"], _n(tt.get("ceiling_m2"), lg, 1), "m²"))
    if len(takeoff.get("levels") or []) > 1:
        kpis.append((T["levels"], str(len(takeoff["levels"])), ""))
    indice = ["Totais globais", "Totais por piso", "Detalhe por divisão", "Modelos de obra aplicados", "Cotas medidas", "Materiais"]
    capa = {"tipo": T["takeoff"], "titulo": plan.get("filename") or T["takeoff"],
            "subtitulo": plan.get("project_name") or "", "local": plan.get("address") or "",
            "data": "", "kpis": kpis, "indice": indice}
    return acabar(pdf, capa, branding, lg, paginas="completo")


def acabar_orcamento_medicao(pdf: bytes, quote: dict, branding: dict | None, lang: str | None = None) -> bytes:
    lg = lang_of(lang, (branding or {}).get("country"))
    T = TXT[lg]
    ttc, ht = _eur(quote.get("total_ttc"), lg), _eur(quote.get("subtotal_ht"), lg)
    mat, mo = _eur(quote.get("subtotal_material"), lg), _eur(quote.get("subtotal_labour"), lg)
    tt = quote.get("totals") or {}
    kpis = [(T["total_ttc"], ttc[0], ttc[1]), (T["total_ht"], ht[0], ht[1]), (T["material"], mat[0], mat[1]),
            (T["labour"], mo[0], mo[1]), (T["floor"], _n(tt.get("floor_m2"), lg, 1), "m²"),
            (T["walls"], _n(tt.get("walls_net_m2"), lg, 1), "m²"),
            (T["lines"], str(len(quote.get("line_items") or [])), T["items"])]
    capa = {"tipo": T["quote"], "titulo": quote.get("filename") or T["quote"], "subtitulo": "", "local": "", "data": "",
            "kpis": kpis, "indice": ["Áreas medidas", "Detalhe dos artigos", "Resumo"]}
    return acabar(pdf, capa, branding, lg, paginas="completo")
