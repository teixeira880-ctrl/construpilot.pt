// Recommandation : on arrondit TOUJOURS vers le haut (marge de croissance de 40 %) et le suivi
// de chantier / coûts réels mène à Business, seule offre en ligne qui l'inclut entièrement.
export function recommendPlan(plans, { users, projects, site }) {
  const order = ["solo", "professional", "business", "enterprise"];
  const byKey = Object.fromEntries(plans.map((p) => [p.key, p]));
  const fits = (k) => {
    const l = byKey[k]?.limits;
    if (!l) return false;
    return users <= l.seats && projects * 1.4 <= l.active_projects;
  };
  let pick = order.find(fits) || "enterprise";
  if (site && order.indexOf(pick) < order.indexOf("business")) pick = "business";
  if (users > 1 && pick === "solo") pick = "professional";
  return pick;
}
