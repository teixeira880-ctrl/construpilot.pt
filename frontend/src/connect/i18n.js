export function fmt(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Texto i18n de um objeto do catálogo ({pt, en, fr}). */
export function tr(obj, lang) {
  if (!obj) return "";
  if (typeof obj === "string") return obj;
  return obj[lang] || obj.pt || "";
}

function initialLang() {
  try {
    const q = new URLSearchParams(window.location.search).get("lang");
    if (CONNECT_LANGS.includes(q)) return q;
    const s = localStorage.getItem(KEY);
    if (CONNECT_LANGS.includes(s)) return s;
    const g = localStorage.getItem("construpilot_lang");
    if (CONNECT_LANGS.includes(g)) return g;
  } catch { /* armazenamento indisponível */ }
  return "pt";
}

/** Idioma próprio do /connect: troca instantânea, sem recarregar (as respostas não se perdem). */
export function useConnectLang() {
  const [lang, setLangState] = useState(initialLang);
  useEffect(() => {
    try { document.documentElement.lang = lang === "pt" ? "pt-PT" : lang; } catch { /* noop */ }
  }, [lang]);
  const setLang = useCallback((l) => {
    if (!CONNECT_LANGS.includes(l)) return;
    try { localStorage.setItem(KEY, l); } catch { /* noop */ }
    setLangState(l);
  }, []);
  const t = useCallback((key, vars) => {
    const v = key.split(".").reduce((o, k) => (o == null ? o : o[k]), UI[lang]);
    const fallback = key.split(".").reduce((o, k) => (o == null ? o : o[k]), UI.pt);
    const out = v ?? fallback ?? key;
    return typeof out === "string" ? fmt(out, vars) : out;
  }, [lang]);
  return { lang, setLang, t };
}

export function formatEurLang(v, lang, decimals = 0) {
  const loc = lang === "en" ? "en-IE" : lang === "fr" ? "fr-FR" : "pt-PT";
  return new Intl.NumberFormat(loc, { style: "currency", currency: "EUR", minimumFractionDigits: decimals, maximumFractionDigits: decimals }).format(Number(v || 0));
}

export function formatNum(v, lang, decimals = 2) {
  const loc = lang === "en" ? "en-IE" : lang === "fr" ? "fr-FR" : "pt-PT";
  return new Intl.NumberFormat(loc, { maximumFractionDigits: decimals }).format(Number(v || 0));
}
