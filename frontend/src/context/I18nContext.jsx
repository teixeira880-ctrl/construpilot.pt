const STORAGE_KEY = "construpilot_lang";
const SUPPORTED = ["fr", "en", "es", "pt", "it", "de", "ar"];
const RTL_LANGS = ["ar"];

function detectLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && SUPPORTED.includes(stored)) return stored;
  // Lançamento em Portugal : deteta visitantes de Portugal (idioma/fuso horário
  // do navegador ou domínio .pt) e abre automaticamente em PT-PT.
  try {
    const host = (window.location.hostname || "").toLowerCase();
    if (host.endsWith(".pt")) return "pt";
    const nav = (navigator.language || navigator.userLanguage || "").toLowerCase();
    const langs = [nav, ...((navigator.languages || []).map((l) => l.toLowerCase()))];
    if (langs.some((l) => l === "pt" || l === "pt-pt")) return "pt";
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
    if (["Europe/Lisbon", "Atlantic/Madeira", "Atlantic/Azores"].includes(tz)) return "pt";
  } catch { /* SSR / navegador restrito */ }
  // Produit français-first (construpilot.fr) : FR par défaut, l'utilisateur peut changer.
  return "fr";
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detectLang);

  const applyDir = (l) => {
    document.documentElement.lang = l;
    document.documentElement.dir = RTL_LANGS.includes(l) ? "rtl" : "ltr";
  };

  const setLang = (l) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
    applyDir(l);
    // Sync best-effort vers le backend si l'utilisateur est connecté (emails multilingues).
    if (localStorage.getItem("construpilot_token")) {
      import("@/lib/api").then(({ api }) => api.put("/auth/language", { lang: l }).catch(() => {}));
    }
  };

  useEffect(() => { applyDir(lang); }, [lang]);

  const t = (key, fallback = "") =>
    TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.fr[key] ?? fallback ?? key;

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

