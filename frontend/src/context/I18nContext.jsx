const STORAGE_KEY = "construpilot_lang";
const SUPPORTED = ["fr", "en", "es", "pt", "it", "de", "ar"];
const RTL_LANGS = ["ar"];

function detectLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && SUPPORTED.includes(stored)) return stored;
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "fr";
  const code = nav.slice(0, 2).toLowerCase();
  return SUPPORTED.includes(code) ? code : "fr";
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detectLang);

  const applyDir = (l) => {
    document.documentElement.lang = l;
    document.documentElement.dir = RTL_LANGS.includes(l) ? "rtl" : "ltr";
  };

  const setLang = (l) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
    applyDir(l);
  };

  useEffect(() => { applyDir(lang); }, [lang]);

  const t = (key, fallback = "") =>
    TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.fr[key] ?? fallback ?? key;

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

